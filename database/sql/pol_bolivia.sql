        CHECK (btrim(url) <> ''),

    CONSTRAINT fotos_mascota_orden_valido
        CHECK (orden > 0),

    -- Un video no puede ser la imagen principal.
    CONSTRAINT fotos_mascota_principal_solo_foto
        CHECK (tipo = 'foto' OR es_principal = FALSE)
