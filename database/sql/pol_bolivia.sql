CREATE OR REPLACE FUNCTION validar_limite_visitas()
RETURNS TRIGGER AS $$
DECLARE
    cantidad INTEGER;
BEGIN
    -- Serializa el conteo de visitas del mismo caso.
    PERFORM 1
    FROM seguimientos_adopcion
    WHERE id = NEW.seguimiento_id
    FOR UPDATE;

    SELECT COUNT(*) INTO cantidad
    FROM visitas_seguimiento
    WHERE seguimiento_id = NEW.seguimiento_id
      AND id IS DISTINCT FROM NEW.id;

    IF cantidad >= 2 THEN
        RAISE EXCEPTION 'Una adopción no puede tener más de 2 visitas de seguimiento';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

