CREATE TABLE mascotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,
    especie VARCHAR(50) NOT NULL,                   -- FILTRO (solo perro/gato)
    raza VARCHAR(100),                              -- INFORMATIVO (NO FILTRO)
    edad SMALLINT NOT NULL CHECK (edad >= 0),       -- FILTRO (con rangos) — CORRECCIÓN: ahora obligatoria
    sexo VARCHAR(10) NOT NULL,                      -- FILTRO
