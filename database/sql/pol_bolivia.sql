    estado VARCHAR(20) NOT NULL DEFAULT 'borrador',

    -- RESTRICT conserva la trazabilidad de quién registró la mascota.
    registrado_por BIGINT NOT NULL
        REFERENCES usuarios(id)
        ON DELETE RESTRICT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT mascotas_sexo_valido
        CHECK (sexo IN ('macho', 'hembra')),

    CONSTRAINT mascotas_estado_valido
        CHECK (estado IN ('borrador', 'disponible', 'adoptada')),

    CONSTRAINT mascotas_tamano_valido
        CHECK (tamano IN ('pequeno', 'mediano', 'grande')),

    -- CORRECCIÓN: el sistema solo maneja perros y gatos
    CONSTRAINT mascotas_especie_valida
        CHECK (especie IN ('perro', 'gato')),

    -- CORRECCIÓN: evita nombre de mascota en blanco
    CONSTRAINT mascotas_nombre_no_vacio
        CHECK (btrim(nombre) <> '')
);

