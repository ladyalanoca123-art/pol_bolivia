-- La FK compuesta valida que postulación y usuario sean de la misma persona.
-- Este trigger completa la regla: el perfil solo existe desde una postulación
-- aprobada y para una cuenta activa cuyo rol ya fue promovido a voluntario.
CREATE OR REPLACE FUNCTION validar_voluntario_desde_postulacion()
RETURNS TRIGGER AS $$
DECLARE
    estado_postulacion VARCHAR(20);
    usuario_postulacion BIGINT;
    rol_usuario VARCHAR(20);
    activo_usuario BOOLEAN;
BEGIN
    SELECT p.estado, p.usuario_id, u.rol, u.estado
    INTO estado_postulacion, usuario_postulacion, rol_usuario, activo_usuario
    FROM postulaciones_voluntariado p
    JOIN usuarios u ON u.id = NEW.usuario_id
    WHERE p.id = NEW.postulacion_id;

    IF estado_postulacion IS NULL THEN
        RAISE EXCEPTION 'La postulación indicada no existe';
    END IF;

    IF usuario_postulacion IS DISTINCT FROM NEW.usuario_id THEN
        RAISE EXCEPTION
            'La postulación indicada no corresponde al usuario del voluntario';
    END IF;

    IF estado_postulacion <> 'aprobada' THEN
        RAISE EXCEPTION
            'Solo una postulación aprobada puede generar un perfil de voluntario';
    END IF;

    IF rol_usuario IS DISTINCT FROM 'voluntario'
       OR activo_usuario IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION
            'El perfil requiere un usuario voluntario con cuenta activa';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_voluntario_desde_postulacion
BEFORE INSERT OR UPDATE OF usuario_id, postulacion_id ON voluntarios
FOR EACH ROW
EXECUTE FUNCTION validar_voluntario_desde_postulacion();

