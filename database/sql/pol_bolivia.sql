    ON fotos_mascota(mascota_id)
    WHERE tipo = 'video';

-- CORRECCIÓN: dos fotos de la misma mascota no pueden compartir el mismo orden
-- (evita ambigüedad sobre cuál mostrar primero).
CREATE UNIQUE INDEX idx_orden_unico_por_mascota
    ON fotos_mascota(mascota_id, orden)
    WHERE tipo = 'foto';


-- ============================================
-- 3. Trigger: máximo 4 fotos y 1 video
-- ============================================

CREATE OR REPLACE FUNCTION validar_limite_multimedia()
RETURNS TRIGGER AS $$
DECLARE
    cantidad INTEGER;
BEGIN
    -- Serializa altas y cambios de multimedia de la misma mascota.
    -- Sin este bloqueo dos transacciones simultáneas podrían superar el límite.
    PERFORM 1
    FROM mascotas
    WHERE id = NEW.mascota_id
    FOR UPDATE;

    IF NEW.tipo = 'foto' THEN
        SELECT COUNT(*)
        INTO cantidad
        FROM fotos_mascota
        WHERE mascota_id = NEW.mascota_id
          AND tipo = 'foto'
          AND id IS DISTINCT FROM NEW.id;

        IF cantidad >= 4 THEN
            RAISE EXCEPTION
                'Una mascota no puede tener más de 4 fotos';
        END IF;

    ELSIF NEW.tipo = 'video' THEN
        SELECT COUNT(*)
        INTO cantidad
        FROM fotos_mascota
        WHERE mascota_id = NEW.mascota_id
          AND tipo = 'video'
          AND id IS DISTINCT FROM NEW.id;

        IF cantidad >= 1 THEN
            RAISE EXCEPTION
                'Una mascota no puede tener más de 1 video';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_multimedia
BEFORE INSERT OR UPDATE OF mascota_id, tipo ON fotos_mascota
FOR EACH ROW
EXECUTE FUNCTION validar_limite_multimedia();


-- ============================================
-- 4. Trigger: gestionar foto principal
-- ============================================

CREATE OR REPLACE FUNCTION gestionar_foto_principal()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.es_principal = TRUE THEN
        UPDATE fotos_mascota
        SET es_principal = FALSE
        WHERE mascota_id = NEW.mascota_id
          AND id <> NEW.id
          AND tipo = 'foto'
          AND es_principal = TRUE;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_foto_principal
BEFORE INSERT OR UPDATE ON fotos_mascota
FOR EACH ROW
EXECUTE FUNCTION gestionar_foto_principal();

-- Una publicación disponible debe conservar, en todo momento, al menos
-- una foto y una foto principal, incluso después de editar o borrar archivos.
CREATE OR REPLACE FUNCTION validar_multimedia_mascota_publicada()
RETURNS TRIGGER AS $$
DECLARE
    mascota_a_validar BIGINT;
    estado_mascota VARCHAR(20);
    cantidad_fotos INTEGER;
    cantidad_principales INTEGER;
BEGIN
    mascota_a_validar := OLD.mascota_id;

    SELECT estado INTO estado_mascota
    FROM mascotas
    WHERE id = mascota_a_validar;

    IF estado_mascota = 'disponible' THEN
        SELECT COUNT(*) INTO cantidad_fotos
        FROM fotos_mascota
        WHERE mascota_id = mascota_a_validar
          AND tipo = 'foto';

        SELECT COUNT(*) INTO cantidad_principales
        FROM fotos_mascota
        WHERE mascota_id = mascota_a_validar
          AND tipo = 'foto'
          AND es_principal = TRUE;

        IF cantidad_fotos = 0 OR cantidad_principales = 0 THEN
            RAISE EXCEPTION
                'Una mascota disponible debe conservar al menos una foto principal';
        END IF;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trigger_validar_multimedia_publicada
AFTER DELETE OR UPDATE ON fotos_mascota
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validar_multimedia_mascota_publicada();


-- ============================================
-- 5. Validar fotos antes de publicar mascota
-- ============================================

CREATE OR REPLACE FUNCTION validar_minimo_fotos()
RETURNS TRIGGER AS $$
DECLARE
    cantidad_fotos INTEGER;
    cantidad_principales INTEGER;
BEGIN
    IF NEW.estado = 'disponible' THEN
        SELECT COUNT(*)
        INTO cantidad_fotos
        FROM fotos_mascota
        WHERE mascota_id = NEW.id
          AND tipo = 'foto';

        SELECT COUNT(*)
        INTO cantidad_principales
        FROM fotos_mascota
        WHERE mascota_id = NEW.id
          AND tipo = 'foto'
          AND es_principal = TRUE;

        IF cantidad_fotos = 0 THEN
            RAISE EXCEPTION
                'La mascota necesita al menos una foto para poder publicarse';
        END IF;

        IF cantidad_principales = 0 THEN
            RAISE EXCEPTION
                'La mascota necesita una foto principal para poder publicarse';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_minimo_fotos
BEFORE INSERT OR UPDATE ON mascotas
FOR EACH ROW
EXECUTE FUNCTION validar_minimo_fotos();


