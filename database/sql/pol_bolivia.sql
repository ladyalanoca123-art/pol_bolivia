-- ============================================
-- MÓDULO 1 — GESTIÓN DE USUARIOS
-- Tabla: usuarios
-- ============================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo CITEXT NOT NULL,
    telefono VARCHAR(20),
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'ciudadano',
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ NULL,
    remember_token VARCHAR(100) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuarios_correo_unico UNIQUE (correo),
    CONSTRAINT usuarios_correo_no_vacio
        CHECK (btrim(correo::text) <> ''),
    CONSTRAINT usuarios_password_no_vacio
        CHECK (btrim(password) <> ''),
    -- SEGURIDAD / INTEGRIDAD: el teléfono es opcional, pero no puede ser solo espacios.
    CONSTRAINT usuarios_telefono_no_vacio
        CHECK (telefono IS NULL OR btrim(telefono) <> ''),
    CONSTRAINT usuarios_rol_valido
        CHECK (rol IN ('administrador', 'voluntario', 'ciudadano')),

    -- CORRECCIÓN: evita nombres/apellidos en blanco (NOT NULL no lo evita)
    CONSTRAINT usuarios_nombres_no_vacio
        CHECK (btrim(nombres) <> ''),
    CONSTRAINT usuarios_apellidos_no_vacio
        CHECK (btrim(apellidos) <> '')
);

-- Índice para búsquedas frecuentes por rol
CREATE INDEX idx_usuarios_rol ON usuarios(rol);

-- Función y trigger para mantener updated_at actualizado automáticamente
CREATE OR REPLACE FUNCTION actualizar_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_usuarios_updated_at
BEFORE UPDATE ON usuarios
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();


