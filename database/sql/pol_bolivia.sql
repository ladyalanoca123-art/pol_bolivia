-- ============================================
-- PROTECCIÓN DEL ESTADO DE MASCOTAS
-- ============================================
-- Una mascota solo llega a 'adoptada' desde el trigger interno que procesa
-- la aceptación de una solicitud. pg_trigger_depth() distingue esa escritura
-- encadenada de un UPDATE directo sobre mascotas, y la solicitud aceptada se
-- comprueba además para la misma mascota.
CREATE OR REPLACE FUNCTION proteger_estado_mascota()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.estado = 'adoptada' THEN
        RAISE EXCEPTION
            'Una mascota no puede crearse directamente con estado adoptada';
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.estado = 'adoptada' AND NEW.estado <> OLD.estado THEN
            RAISE EXCEPTION
                'Una mascota adoptada no puede cambiar nuevamente de estado';
        END IF;

        IF NEW.estado = 'adoptada' AND OLD.estado <> 'adoptada' THEN
            IF pg_trigger_depth() < 2
               OR NOT EXISTS (
                    SELECT 1
                    FROM solicitudes_adopcion
                    WHERE mascota_id = NEW.id
                      AND estado = 'aceptada'
               ) THEN
                RAISE EXCEPTION
                    'El estado adoptada solo puede establecerse al aceptar una solicitud';
            END IF;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_proteger_estado_mascota
BEFORE INSERT OR UPDATE OF estado ON mascotas
FOR EACH ROW
EXECUTE FUNCTION proteger_estado_mascota();

-- ============================================
-- DEPENDENCIA CRUZADA: ADOPCIÓN -> SEGUIMIENTO
-- ============================================
-- Al aceptar una solicitud, adopta la mascota, cierra las demás solicitudes
-- activas (pendientes o en espera) y crea el caso de seguimiento.
-- Se define aquí, después de crear seguimientos_adopcion, para mantener
-- el orden natural de dependencias del script.
CREATE OR REPLACE FUNCTION procesar_aceptacion_solicitud()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.estado = 'aceptada'
       AND OLD.estado <> 'aceptada' THEN

        UPDATE mascotas
        SET estado = 'adoptada'
        WHERE id = NEW.mascota_id;

        UPDATE solicitudes_adopcion
        SET estado = 'cerrada'
        WHERE mascota_id = NEW.mascota_id
          AND id <> NEW.id
          AND estado IN ('pendiente', 'en_espera');

        -- Crea el caso de seguimiento, copiando zona y horario
        -- que el ciudadano indicó en su solicitud.
        INSERT INTO seguimientos_adopcion (solicitud_id, zona_aproximada, horario_preferido)
        VALUES (NEW.id, NEW.zona_aproximada, NEW.horario_preferido);

    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_procesar_aceptacion
AFTER UPDATE OF estado ON solicitudes_adopcion
FOR EACH ROW
EXECUTE FUNCTION procesar_aceptacion_solicitud();


