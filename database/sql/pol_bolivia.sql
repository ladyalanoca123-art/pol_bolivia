-- ============================================
-- 1. Vista: resumen general (KPIs para el dashboard del admin)
-- Devuelve una sola fila con los indicadores clave del sistema.
-- ============================================

CREATE OR REPLACE VIEW vista_resumen_general AS
SELECT
    (SELECT COUNT(*) FROM mascotas WHERE estado = 'disponible')
        AS mascotas_disponibles,
    (SELECT COUNT(*) FROM mascotas WHERE estado = 'adoptada')
        AS mascotas_adoptadas_total,
    (SELECT COUNT(*) FROM solicitudes_adopcion
        WHERE estado = 'aceptada'
          AND updated_at >= date_trunc('month', CURRENT_DATE))
        AS adopciones_este_mes,
    (SELECT COUNT(*) FROM solicitudes_adopcion WHERE estado = 'pendiente')
        AS solicitudes_pendientes,
    (SELECT COUNT(*) FROM seguimientos_adopcion WHERE estado = 'activo')
        AS seguimientos_activos,
    (SELECT COUNT(*) FROM seguimientos_adopcion WHERE estado = 'sin_asignar')
        AS seguimientos_sin_asignar,
    (SELECT COUNT(*) FROM incidencias WHERE estado <> 'atendida')
        AS incidencias_sin_atender,
    (SELECT COUNT(*) FROM voluntarios WHERE estado = 'activo')
        AS voluntarios_activos,
    (SELECT COUNT(*) FROM postulaciones_voluntariado WHERE estado = 'pendiente')
        AS postulaciones_pendientes;


-- ============================================
-- 2. Vista: adopciones realizadas
-- ============================================

CREATE OR REPLACE VIEW vista_adopciones_realizadas AS
SELECT
    s.id                          AS solicitud_id,
    m.id                          AS mascota_id,
    m.nombre                      AS mascota_nombre,
    m.especie,
    u.id                          AS adoptante_id,
    u.nombres || ' ' || u.apellidos AS adoptante_nombre,
    s.updated_at                  AS fecha_adopcion,
    sg.id                         AS seguimiento_id,
    sg.estado                     AS estado_seguimiento,
    sg.voluntario_id
FROM solicitudes_adopcion s
JOIN mascotas m ON m.id = s.mascota_id
JOIN usuarios u ON u.id = s.solicitante_id
LEFT JOIN seguimientos_adopcion sg ON sg.solicitud_id = s.id
WHERE s.estado = 'aceptada';


-- ============================================
-- 3. Vista: catálogo de mascotas disponibles (agrupado, para gráficos)
-- Reutiliza mascotas_con_rango (Módulo 2) para el rango de edad.
-- ============================================

CREATE OR REPLACE VIEW vista_mascotas_disponibles_catalogo AS
SELECT
    especie,
    tamano,
    sexo,
    rango_edad,
    COUNT(*) AS cantidad
FROM mascotas_con_rango
WHERE estado = 'disponible'
GROUP BY especie, tamano, sexo, rango_edad
ORDER BY especie, tamano, sexo, rango_edad;


-- ============================================
-- 4. Vista: seguimientos activos (para el tablero de seguimiento)
-- ============================================

CREATE OR REPLACE VIEW vista_seguimientos_activos AS
SELECT
    sg.id                             AS seguimiento_id,
    m.nombre                          AS mascota_nombre,
    m.especie,
    ua.nombres || ' ' || ua.apellidos AS adoptante_nombre,
    uv.nombres || ' ' || uv.apellidos AS voluntario_nombre,
    sg.fecha_inicio,
    (CURRENT_DATE - sg.fecha_inicio::date) AS dias_transcurridos,
    (SELECT COUNT(*) FROM visitas_seguimiento v
        WHERE v.seguimiento_id = sg.id AND v.estado = 'realizada')
        AS visitas_realizadas,
    (SELECT COUNT(*) FROM incidencias i
        WHERE i.seguimiento_id = sg.id AND i.estado <> 'atendida')
        AS incidencias_pendientes
FROM seguimientos_adopcion sg
JOIN solicitudes_adopcion s ON s.id = sg.solicitud_id
JOIN mascotas m ON m.id = s.mascota_id
JOIN usuarios ua ON ua.id = s.solicitante_id
LEFT JOIN usuarios uv ON uv.id = sg.voluntario_id
WHERE sg.estado = 'activo';


-- ============================================
-- 5. Vista: participación de voluntarios
-- ============================================

CREATE OR REPLACE VIEW vista_participacion_voluntarios AS
SELECT
    u.id                             AS voluntario_id,
    u.nombres || ' ' || u.apellidos  AS voluntario_nombre,
    v.estado                         AS estado_perfil,
    (SELECT COUNT(*) FROM seguimientos_adopcion sg
        WHERE sg.voluntario_id = u.id AND sg.estado = 'activo')
        AS casos_activos,
    (SELECT COUNT(*) FROM seguimientos_adopcion sg
        WHERE sg.voluntario_id = u.id AND sg.estado = 'cerrado')
        AS casos_cerrados,
    (SELECT COUNT(*) FROM visitas_seguimiento vs
        WHERE vs.voluntario_id = u.id AND vs.estado = 'realizada')
        AS visitas_realizadas,
    (SELECT COUNT(*) FROM incidencias i
        WHERE i.atendida_por = u.id)
        AS incidencias_atendidas
FROM usuarios u
JOIN voluntarios v ON v.usuario_id = u.id
ORDER BY casos_activos DESC;


