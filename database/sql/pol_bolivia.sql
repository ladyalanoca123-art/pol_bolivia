-- Una solicitud representa a una persona y una mascota concretas. Para
-- cambiar cualquiera de ambas se debe registrar una nueva solicitud.
CREATE OR REPLACE FUNCTION validar_datos_inmutables_solicitud()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.mascota_id IS DISTINCT FROM OLD.mascota_id
       OR NEW.solicitante_id IS DISTINCT FROM OLD.solicitante_id THEN
        RAISE EXCEPTION
            'No se puede cambiar la mascota ni el solicitante de una solicitud existente';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_datos_inmutables_solicitud
BEFORE UPDATE OF mascota_id, solicitante_id ON solicitudes_adopcion
FOR EACH ROW
EXECUTE FUNCTION validar_datos_inmutables_solicitud();

-- Control de cambios de estado.
-- El backend autoriza quién puede cancelar; la base garantiza el flujo:
-- pendiente -> en_espera/aceptada/rechazada/cancelada
-- en_espera -> pendiente/aceptada/rechazada/cancelada
-- cerrada se usa exclusivamente al aceptar otra solicitud para la misma mascota.
CREATE OR REPLACE FUNCTION validar_cambio_estado_solicitud()
RETURNS TRIGGER AS $$
DECLARE
    estado_mascota VARCHAR(20);
BEGIN
    IF OLD.estado IN ('aceptada', 'rechazada', 'cancelada', 'cerrada')
       AND NEW.estado <> OLD.estado THEN
        RAISE EXCEPTION
            'Una solicitud con estado final no puede cambiar de estado';
    END IF;

    -- El cierre se permite solo durante el UPDATE anidado que ejecuta
    -- procesar_aceptacion_solicitud. Una actualización directa entra a este
    -- trigger con profundidad 1; el UPDATE interno del trigger de aceptación,
    -- con profundidad mayor que 1.
    IF NEW.estado = 'cerrada'
       AND OLD.estado <> 'cerrada'
       AND pg_trigger_depth() = 1 THEN
        RAISE EXCEPTION
            'El estado cerrada solo puede asignarse automáticamente al aceptar otra solicitud';
    END IF;

    IF NEW.estado = 'aceptada'
       AND OLD.estado NOT IN ('pendiente', 'en_espera') THEN
        RAISE EXCEPTION
            'Solo se puede aceptar una solicitud pendiente o en espera';
    END IF;

    IF NEW.estado = 'aceptada' AND OLD.estado <> 'aceptada' THEN
        -- Bloquea la mascota durante la decisión para evitar dos aceptaciones
        -- concurrentes o aceptar una mascota que ya dejó de estar disponible.
        SELECT estado INTO estado_mascota
        FROM mascotas
        WHERE id = NEW.mascota_id
        FOR UPDATE;

        IF estado_mascota IS DISTINCT FROM 'disponible' THEN
            RAISE EXCEPTION
                'Solo se puede aceptar una solicitud de una mascota disponible';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_cambio_estado_solicitud
BEFORE UPDATE OF estado ON solicitudes_adopcion
FOR EACH ROW
EXECUTE FUNCTION validar_cambio_estado_solicitud();

