       AND (NEW.revisado_por IS NOT NULL OR NEW.revisado_at IS NOT NULL) THEN
        RAISE EXCEPTION
            'Una postulación cancelada no puede conservar datos de revisión';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

