-- Solo se permiten solicitudes para mascotas disponibles.
CREATE OR REPLACE FUNCTION validar_mascota_disponible()
RETURNS TRIGGER AS $$
DECLARE
    estado_mascota VARCHAR(20);
BEGIN
    -- Bloquea la mascota durante la validación. Así una aceptación concurrente
    -- no puede dejar una solicitud pendiente para una mascota ya adoptada.
    SELECT estado
    INTO estado_mascota
    FROM mascotas
    WHERE id = NEW.mascota_id
    FOR UPDATE;

    IF estado_mascota IS NULL THEN
        RAISE EXCEPTION 'La mascota indicada no existe';
    END IF;

    IF estado_mascota <> 'disponible' THEN
        RAISE EXCEPTION 'Esta mascota ya no está disponible para adopción';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_mascota_disponible
BEFORE INSERT OR UPDATE OF mascota_id ON solicitudes_adopcion
FOR EACH ROW
EXECUTE FUNCTION validar_mascota_disponible();

-- CORRECCIÓN: solo un ciudadano con cuenta activa puede solicitar una adopción.
CREATE OR REPLACE FUNCTION validar_solicitante_valido()
RETURNS TRIGGER AS $$
DECLARE
    rol_usuario VARCHAR(20);
    activo_usuario BOOLEAN;
BEGIN
    SELECT rol, estado INTO rol_usuario, activo_usuario
    FROM usuarios
    WHERE id = NEW.solicitante_id;

    IF rol_usuario IS DISTINCT FROM 'ciudadano' THEN
        RAISE EXCEPTION 'Solo un usuario con rol ciudadano puede solicitar una adopción';
    END IF;

    IF activo_usuario IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'El solicitante debe tener una cuenta activa';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_solicitante_valido
BEFORE INSERT OR UPDATE OF solicitante_id ON solicitudes_adopcion
FOR EACH ROW
EXECUTE FUNCTION validar_solicitante_valido();

