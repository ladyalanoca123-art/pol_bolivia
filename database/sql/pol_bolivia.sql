-- Solo un ciudadano activo puede postularse, y no si ya tiene
-- un perfil de voluntario activo.
CREATE OR REPLACE FUNCTION validar_postulante_valido()
RETURNS TRIGGER AS $$
DECLARE
    rol_usuario VARCHAR(20);
    activo_usuario BOOLEAN;
BEGIN
    SELECT rol, estado INTO rol_usuario, activo_usuario
    FROM usuarios
    WHERE id = NEW.usuario_id;

    IF rol_usuario IS DISTINCT FROM 'ciudadano' THEN
        RAISE EXCEPTION 'Solo un usuario con rol ciudadano puede postularse como voluntario';
    END IF;

    IF activo_usuario IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'El postulante debe tener una cuenta activa';
    END IF;

    IF EXISTS (
        SELECT 1 FROM voluntarios
        WHERE usuario_id = NEW.usuario_id
          AND estado = 'activo'
    ) THEN
        RAISE EXCEPTION 'El usuario ya tiene un perfil de voluntario activo';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_validar_postulante_valido
BEFORE INSERT OR UPDATE OF usuario_id ON postulaciones_voluntariado
FOR EACH ROW
EXECUTE FUNCTION validar_postulante_valido();


-- Al aprobar: sube el rol del usuario a 'voluntario' y crea (o reactiva)
-- su perfil en la tabla voluntarios.
CREATE OR REPLACE FUNCTION procesar_aprobacion_postulacion()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.estado = 'aprobada' AND OLD.estado <> 'aprobada' THEN

        UPDATE usuarios
        SET rol = 'voluntario'
        WHERE id = NEW.usuario_id;

        IF EXISTS (SELECT 1 FROM voluntarios WHERE usuario_id = NEW.usuario_id) THEN
            UPDATE voluntarios
            SET estado = 'activo',
                postulacion_id = NEW.id,
                habilidades = NEW.habilidades,
                disponibilidad = NEW.disponibilidad,
                zona_preferencia = NEW.zona_preferencia,
                updated_at = CURRENT_TIMESTAMP
            WHERE usuario_id = NEW.usuario_id;
        ELSE
            INSERT INTO voluntarios (usuario_id, postulacion_id, habilidades, disponibilidad, zona_preferencia)
            VALUES (NEW.usuario_id, NEW.id, NEW.habilidades, NEW.disponibilidad, NEW.zona_preferencia);
        END IF;

    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_procesar_aprobacion_postulacion
AFTER UPDATE OF estado ON postulaciones_voluntariado
FOR EACH ROW
EXECUTE FUNCTION procesar_aprobacion_postulacion();


-- Evita dejar casos activos asignados a cuentas inactivas o sin rol de voluntario.
CREATE OR REPLACE FUNCTION proteger_voluntario_asignado()
RETURNS TRIGGER AS $$
BEGIN
    -- La baja normal primero cambia voluntarios.estado a 'inactivo' y luego
    -- este trigger permite devolver la cuenta al rol ciudadano.
    IF (NEW.rol <> 'voluntario' OR NEW.estado = FALSE)
       AND EXISTS (
           SELECT 1
           FROM voluntarios
           WHERE usuario_id = OLD.id
             AND estado = 'activo'
       ) THEN
        RAISE EXCEPTION
            'Primero debe darse de baja el perfil activo del voluntario';
    END IF;

    IF (NEW.rol <> 'voluntario' OR NEW.estado = FALSE)
       AND EXISTS (
           SELECT 1
           FROM seguimientos_adopcion
           WHERE voluntario_id = OLD.id
             AND estado = 'activo'
       ) THEN
        RAISE EXCEPTION
            'No se puede cambiar el rol ni desactivar a un voluntario con seguimientos activos';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_proteger_voluntario_asignado
BEFORE UPDATE OF rol, estado ON usuarios
FOR EACH ROW
EXECUTE FUNCTION proteger_voluntario_asignado();

-- Al dar de baja al voluntario, su cuenta vuelve a rol 'ciudadano'.
-- Si tiene seguimientos activos asignados, trigger_proteger_voluntario_asignado
-- (Módulo 3) bloqueará este UPDATE en cascada, evitando dejar casos huérfanos.
CREATE OR REPLACE FUNCTION procesar_baja_voluntario()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.estado = 'inactivo' AND OLD.estado <> 'inactivo' THEN
        UPDATE usuarios
        SET rol = 'ciudadano'
        WHERE id = NEW.usuario_id
          AND rol = 'voluntario';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_procesar_baja_voluntario
AFTER UPDATE OF estado ON voluntarios
FOR EACH ROW
EXECUTE FUNCTION procesar_baja_voluntario();


